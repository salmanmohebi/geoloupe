"""Colormap lookup tables and server-side colouring (for PNG tiles).

The tables live in ``colormaps.json`` (generated by scripts/build_colormaps.py)
and are also sent to the web client, so both render identical colours.
"""

from __future__ import annotations

import json
from functools import lru_cache
from importlib import resources
from typing import Any

import numpy as np


@lru_cache(maxsize=1)
def colormap_table() -> dict[str, dict[str, Any]]:
    """{name: {"category", "provider", "lut" (hex RGB × 256)}}."""
    text = resources.files("geoloupe").joinpath("colormaps.json").read_text()
    data: dict[str, dict[str, Any]] = json.loads(text)
    return data


@lru_cache(maxsize=64)
def lut(name: str) -> np.ndarray:
    """(256, 3) uint8 RGB table. A ``_r`` suffix reverses any colormap."""
    table = colormap_table()
    base, reverse = name, False
    if name not in table and name.endswith("_r") and name[:-2] in table:
        base, reverse = name[:-2], True
    if base not in table:
        raise KeyError(f"unknown colormap {name!r}; available: {', '.join(sorted(table))}")
    rgb = np.frombuffer(bytes.fromhex(table[base]["lut"]), dtype=np.uint8).reshape(256, 3)
    return rgb[::-1].copy() if reverse else rgb


def apply_colormap(
    data: np.ndarray, cmap: str, vmin: float, vmax: float, log_scale: bool = False
) -> np.ndarray:
    """Map float data to (h, w, 4) RGBA uint8; NaN becomes transparent."""
    if not np.isfinite(vmin) or not np.isfinite(vmax) or vmax == vmin:
        raise ValueError("vmin and vmax must be finite and different")
    with np.errstate(invalid="ignore", divide="ignore"):
        if log_scale:
            if vmin <= 0:
                raise ValueError("a log scale needs vmin > 0")
            t = (np.log(data) - np.log(vmin)) / (np.log(vmax) - np.log(vmin))
        else:
            t = (data - vmin) / (vmax - vmin)
    ok = np.isfinite(t)
    idx = np.clip(np.where(ok, t, 0.0) * 255.0 + 0.5, 0, 255).astype(np.uint8)
    rgba = np.empty((*data.shape, 4), dtype=np.uint8)
    rgba[..., :3] = lut(cmap)[idx]
    rgba[..., 3] = np.where(ok, 255, 0)
    return rgba


def apply_classes(
    data: np.ndarray, classes: dict[int, dict[str, str | None]], cmap: str
) -> np.ndarray:
    """Colour class codes (categorical data) with their class colours, like the web client.

    Classes without a colour take evenly spaced colours of ``cmap``; values that are not a class
    (and NaN) are transparent.
    """
    rgba = np.zeros((*data.shape, 4), dtype=np.uint8)
    table = lut(cmap)
    n = len(classes)
    for i, (value, c) in enumerate(sorted(classes.items())):
        color = c.get("color")
        if color:
            rgb = np.frombuffer(bytes.fromhex(color.lstrip("#")[:6]), dtype=np.uint8)
        else:
            rgb = table[round((i / (n - 1) if n > 1 else 0.5) * 255)]
        hit = data == value
        rgba[hit, :3] = rgb
        rgba[hit, 3] = 255
    return rgba
